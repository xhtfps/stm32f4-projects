void OS_Init()
{
	System_init();
	//LED_Init();
	GPIO_Key_Init();
	ADC1_Init();
	ADC2_Init();
	DAC1_Init();
	/**********LCD初始化******************/
	OS_LCD_Init();	//LCD
	
	Touch_Init(); 	//触屏
	
	GPIOTEST_Init();
}

//PA4用作DAC，PC13F4设计缘故，PB1接LED4，但串口未接到F4芯片

int main()
{
	//Task_Create(LED_main,&TASK_0_STK[128-1],0);
	Task_Create(Touch_main,&TASK_1_STK[256-1],1);
	//Task_Create(Switch_main,&TASK_2_STK[256-1],2);
	Task_Create(ADC_main,&TASK_3_STK[256-1],3);
	Task_Create(DAC_main,&TASK_4_STK[256-1],4);
	//Task_Create(GPIOTEST_main,&TASK_5_STK[1024-1],5);
	
	
	//OSTaskSuspend(5);    //挂起任务
	OS_Init();
	OS_Start();
}


