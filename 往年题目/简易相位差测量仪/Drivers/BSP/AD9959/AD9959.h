#ifndef _DRIVE_AD9959_H_
#define _DRIVE_AD9959_H_

/**
 * @file    Drive_AD9959.h
 * @brief   AD9959 四通道 DDS 驱动接口
 *
 * 提供 AD9959 初始化及频率、幅值、相位设置函数。
 * 所有通道参数通过回调最终调用底层统一接口。
 */

#include "sys.h"
#include "stdint.h"

/* ================================================================
 * 初始化
 * ================================================================ */
void Init_AD9959(void);                         /**< 初始化 AD9959 通信与默认配置 */

/* ================================================================
 * 频率设置
 * ================================================================ */
void Write_frequence(u8 Channel, u32 Freq);     /**< 设置指定通道频率并立即更新输出 */
void Write_frequence_no_update(u8 Channel, u32 Freq); /**< 设置频率但不立即更新（实际仍会更新） */

/* ================================================================
 * 幅值设置
 * ================================================================ */
void Write_Amplitude(u8 Channel, u16 Ampli);    /**< 设置指定通道幅值 (mV) 并立即更新输出 */
void Write_Amplitude_no_update(u8 Channel, u16 Ampli); /**< 设置幅值但不立即更新 */

/* ================================================================
 * 相位设置
 * ================================================================ */
void Write_Phase(u8 Channel, u16 Phase);        /**< 设置指定通道相位 (°) 并立即更新输出 */
void Write_Phase_no_update(u8 Channel, u16 Phase); /**< 设置相位但不立即更新 */

/* ================================================================
 * 旧版兼容函数（占位）
 * ================================================================ */
void IntReset(void);                            /**< 中断复位（未使用） */
void IO_Update(void);                           /**< IO 更新（未使用） */
void Intserve(void);                            /**< 中断服务（未使用） */
void AD9959_SyncPhase_All(void);                /**< 同步所有通道相位（未使用） */

#endif
