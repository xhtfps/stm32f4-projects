//-----------------------------------------------------------------
// void LCD_Init (void)
//-----------------------------------------------------------------
//
// 函数功能: LCM初始化
// 入口参数: 无
// 返回参数: 无
// 全局变量: 无
// 调用模块: LCDWrite_com(uchar)    
// 注意事项: 
//     (1)具体流程查看HD44780(KS0066)的中文数据手册;
//-----------------------------------------------------------------
void LCD_Init()
{
	lcden=0;
	LCDWrite_com(0x38);
	LCDWrite_com(0x0c);
	LCDWrite_com(0x06);
	LCDWrite_com(0x01);
	LCDWrite_com(0x80);	  //设置1602指针为第一行第一个
}


