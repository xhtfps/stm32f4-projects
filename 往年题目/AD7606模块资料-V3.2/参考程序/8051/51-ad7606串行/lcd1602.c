//-----------------------------------------------------------------
// LCD_PlayV(uchar add,uint time)
//-----------------------------------------------------------------
//
// 函数功能: LCD显示无符号整型数据
// 入口参数: add:待写的数据的位置  dat：待写的数据
// 返回参数: 无
// 全局变量: 无
// 调用模块: LCDWrite_data();LCDWrite_com()     
// 注意事项:
//-----------------------------------------------------------------
void LCD_PlayV(uchar add,uint dat)
{
	uchar i;
	uchar wei[5];
	wei[0] = (dat/10000)+48;						//万
	wei[1] = ((dat%10000)/1000)+48;			//千
	wei[2] = ((dat%1000)/100)+48;				//百
	wei[3] = ((dat%100)/10)+48;					//十
	wei[4] = (dat%10)+48;							//个
	LCDWrite_com(0x80+add);
	for(i=0; i<5; i++)
	{
		LCDWrite_data(wei[i]);
	}

}

