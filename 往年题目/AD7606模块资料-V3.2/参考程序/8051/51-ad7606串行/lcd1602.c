//-----------------------------------------------------------------------------
// void Delay_ms(uint z)
//-----------------------------------------------------------------------------
//
// 函数功能: 时基为1ms的延时
// 例子提示: 调用Delay_ms(20),得到20ms延时
// 入口参数: 无符号8bit整数
// 返回参数: 无
// 全局变量: 无
// 调用模块: 无
// 注意事项: 基于使用11.0592MHz晶振的51单片机
//-----------------------------------------------------------------------------
void Delay_ms(uint z)
{
	uint x,y;
	for(x=z;x>0;x--)
		for(y=110;y>0;y--);
}


//-----------------------------------------------------------------
// void LCDWrite_com(uchar com)
//-----------------------------------------------------------------
//
// 函数功能: 写LCD的指令代码
// 入口参数: LCD指令
// 返回参数: 无
// 全局变量: 无
// 调用模块: delay(uint z)     
// 注意事项:
//-----------------------------------------------------------------             
void LCDWrite_com(uchar com)
{
	lcdrs=0;
	lcdrw=0;
	lcddat=com;
	Delay_ms(5);
	lcden=1;
	Delay_ms(5);
	lcden=0;
}



//-----------------------------------------------------------------
// void LCDWrite_data(uchar date)
//-----------------------------------------------------------------
//
// 函数功能: 写LCD要显示的数据
// 入口参数: 待写的数据
// 返回参数: 无
// 全局变量: 无
// 调用模块: void Delay_ms()     
// 注意事项:
//-----------------------------------------------------------------
void LCDWrite_data(uchar date)
{	
	lcdrs=1;
	lcdrw=0;
	lcddat=date;
	Delay_ms(5);
	lcden=1;
	Delay_ms(5);
	lcden=0;
}


//-----------------------------------------------------------------
// LCDWrite_word(unsigned char *s)
//-----------------------------------------------------------------
//
// 函数功能: 写LCD要显示的数据（句子）
// 入口参数: 待写的数据（句子）
// 返回参数: 无
// 全局变量: 无
// 调用模块: LCDWrite_data()     
// 注意事项:
//-----------------------------------------------------------------
void LCDWrite_word(unsigned char *s)
{
	while(*s>0)
	{
		LCDWrite_data(*s);
		s++;
	}
}

