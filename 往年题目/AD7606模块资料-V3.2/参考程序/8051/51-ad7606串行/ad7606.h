#define uchar unsigned char
#define uint unsigned int

//-----------------------------------------------------------------
// I/O口定义:ad7606串行读取 SPI接线口
//-----------------------------------------------------------------
sbit AD_RESET = P2^7;
sbit AD_CONVSTB = P2^6;	
sbit AD_CS = P2^4;						//SPI_CS
sbit AD_SCLK = P2^2;					//SPI时钟
sbit AD_FRSTDATA = P2^1;				//数字输出
sbit AD_BUSY = P2^0;					//输出繁忙

 sbit AD_DB7 = P3^7;						//SPI_数据

sbit AD_CONVSTA = P1^7;

sbit AD_OS0 = P1^4;						//过采样模式：0~7 = 无过采样，2倍过采样，4,8,16,32,64，无效
sbit AD_OS1 = P1^5;						//
sbit AD_OS2 = P1^6;						//

