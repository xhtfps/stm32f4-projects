//-----------------------------------------------------------------
// 头文件包含
//-----------------------------------------------------------------
#include <reg52.h>
#include <LCD1602.h>
#include <intrins.h>
#include <ad7606.h>
#include <delay.h>



//-----------------------------------------------------------------
// 数据类型宏定义
//-----------------------------------------------------------------
#define uchar unsigned char
#define uint unsigned int


//-----------------------------------------------------------------
// 函数声明
//-----------------------------------------------------------------


//-----------------------------------------------------------------------------
// 全局变量定义
//-----------------------------------------------------------------------------
uint CH_DATA[9];
uint Volt;
uchar j,fuhao[9];

//-----------------------------------------------------------------------------
// 位定义
//-----------------------------------------------------------------------------


//-----------------------------------------------------------------
// 主程序
//-----------------------------------------------------------------
void main()
{
	LCD_Init();				//
	AD7606_Init();
//	LCDWrite_com(0);
	LCDWrite_word("THE VOLTAGE IS:");
//	LCD_Play(0x40,0x30);
	while(1)
	{

		AD7606_RCHdata();
		LCD_PlayV(0x4b,CH_DATA[2]);			//****				显示数字电压值
		//数据处理
		for(j=0; j<8; j++)
		{
			if(CH_DATA[j]>= 32768)					//负电压（32768~65535）
			{
				CH_DATA[j] = ~(CH_DATA[j]-1);
				fuhao[j] = 1;				//符号标志，1为负，0为正
				CH_DATA[j] *= 1.00441944556;
			}
			else								//正电压（0~32767）
			{ 
				fuhao[j] = 0;
				CH_DATA[j] *= 1.0042177144;
			}
		}
		//选择选择的通道 CH_DATA[],fuhao[].
		LCDWrite_com(0x80+0x40);
		LCDWrite_word("CH2:");			//****
		if(fuhao[2])								//****
		{
			LCDWrite_com(0x80+0x44);			//负号
			LCDWrite_data('-');
		}
		else
		{
			LCDWrite_com(0x80+0x44);	 		//空格
			LCDWrite_data(' ');
		}

		Volt = (1.0*CH_DATA[2]/32767)*10000;			//****	//显示模拟电压并转换成mV显示
		
		//数据处理
	
//		LCD_Play(0x42,Volt);
		LCD_PlayV(0x45,Volt);
		delay_1ms(10); 
		
/*		
		Volt = CH_DATA[0]*1.0/32767*10000;	
		LCD_Play(0x42,Volt/10000);
		LCD_Play(0x44,(Volt%10000)/100);
		LCD_Play(0x46,Volt%100);		
		
		
*/
	}
}


