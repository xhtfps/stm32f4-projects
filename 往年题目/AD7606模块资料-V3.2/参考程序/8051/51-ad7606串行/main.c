//				   (2) 使用内部2.5v基准电压
//           (3) PAR/SER/BYTE SEL接高电平，选择串行
//						   AD_CS	 <-- P2^4;						//SPI_CS
// 							 AD_SCLK 	<-- P2^2;					//SPI时钟
// 							 AD_DB7 	--> P3^7;						//SPI_数据
//
// 							 AD_OS0 <-- P1^4;						//过采样模式：0~7 = 无过采样，2倍过采样，4,8,16,32,64，无效
//  						 AD_OS1 <-- P1^5;						//
// 							 AD_OS2 <-- P1^6;						//
// 							 AD_RESET <-- P2^7;					//复位
//  						 AD_BUSY --> P2^0;					//输出繁忙
// 							 AD_CONVSTA <-- P1^7;				//通道1-4开始信号
// 					 		 AD_CONVSTB <-- P2^6;				//通道5-8开始信号
//  						 AD_FRSTDATA --> P2^1;				//数字输出		
//							 PAR/SER/BYTE SEL  		接高电平			DB15接低电平（也可不接）
//           (5) 调试使用的系统时钟频率Fsysclk=11.0592MHz.
//           (6) 如果先给单片机供电，后给AD模块供电，会一直显示0，这是因为AD模块的复位信号没有给到模块，
//           		 请复位单片机。
