//-----------------------------------------------------------------
// 功能程序区
//-----------------------------------------------------------------
//-----------------------------------------------------------------
// void PeripheralInit(void)
//-----------------------------------------------------------------
// 
// 函数功能: 系统外设初始化
// 入口参数: 无 
// 返 回 值: 无
// 注意事项: 无
//    
//-----------------------------------------------------------------
void PeripheralInit(void)
{
	Delay_5ms (100);
	GPIO_AD7606_Configuration();
	AD7606_Init();;
	LCD_Init();															// 液晶初始化
	
	Set_USBClock();														// USB时钟设置
  USB_Interrupts_Config();									// USB中断初始化
  USB_Init();																// USB初始化
	Delay_5ms (100);
}


