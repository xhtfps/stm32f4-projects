#include <stm32f10x.h>
#include <stdio.h>
#include "Delay.h"
#include "lcd.h"
#include "AD7606.h"
#include "usart.h"
#include "PeripheralInit.h"

//-----------------------------------------------------------------
// 功能程序区
//-----------------------------------------------------------------
//-----------------------------------------------------------------
// void PeripheralInit(void)
//-----------------------------------------------------------------
// 
// 函数功能: 系统外设初始化
// 入口参数: 无 
// 返 回 值: 无
// 注意事项: 无
//    
//-----------------------------------------------------------------
void PeripheralInit(void)
{
	delay_ms (500);
	GPIO_AD7606_Configuration();
	AD7606_Init();
	uart_init(115200);
	LCD_Init();	
															// 液晶初始化
	delay_ms (500);
}


