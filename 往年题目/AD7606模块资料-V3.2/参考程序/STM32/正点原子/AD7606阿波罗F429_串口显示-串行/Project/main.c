/* Includes ------------------------------------------------------------------*/
//-----------------------------------------------------------------
// 头文件包含
//-----------------------------------------------------------------
#include "stm32f429_winner.h"
#include "delay.h"
#include "AD7606.h"
#include "usart.h"
//-----------------------------------------------------------------

//-----------------------------------------------------------------
// 主程序
//-----------------------------------------------------------------
int main(void) 
{
	uint8_t dis_buf[40];
	uint8_t i;
	int16_t DB_data[8] = {0};
  HAL_Init();          												// 初始化HAL库
	SystemClock_Config(360,25,2,8); 						// 设置系统时钟,180Mhz 
  uart_init(115200);													// 串口初始化	
	delay_ms (500);
	GPIO_AD7606_Configuration();								// ad7606引脚初始化
	AD7606_Init();															//ad7606初始化
	delay_ms (500);
	 while (1)
  {	
		AD7606_startconvst();											//ad7606开始转换
		delay_us(1);
		AD7606_read_data(DB_data); 	//读取数据放至数组DB_data[]
		for(i=0;i<8;i++)
		{
			
			sprintf((char*)dis_buf,"CH%1d:%8.1f mv  0x%04x %6d\r\n", i+1, (float)(DB_data[i]*5000.0/32768), (uint16_t)(DB_data[i]^0x8000), (uint16_t)(DB_data[i]^0x8000));	
			delay_ms(10);
			printf("CH%1d:%8.1f mv  0x%04x %6d\r\n", i+1, (float)(DB_data[i]*5000.0/32768), (uint16_t)(DB_data[i]^0x8000), (uint16_t)(DB_data[i]^0x8000));       //在串口显示结果
		}
	  delay_ms(20);
  }
}

